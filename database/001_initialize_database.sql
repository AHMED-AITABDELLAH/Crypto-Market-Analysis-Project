-- Create the project's database schemas.
CREATE SCHEMA IF NOT EXISTS bronze;
CREATE SCHEMA IF NOT EXISTS silver;
CREATE SCHEMA IF NOT EXISTS gold;
-- Keep Airflow's orchestration metadata separate from project market data.
CREATE SCHEMA IF NOT EXISTS airflow_metadata;

-- Bronze: retain each original market event and its Kafka traceability data.
CREATE TABLE IF NOT EXISTS bronze.raw_market_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type TEXT NOT NULL,
    symbol TEXT,
    source TEXT NOT NULL,
    event_time TIMESTAMPTZ,
    ingestion_time TIMESTAMPTZ NOT NULL,
    payload JSONB NOT NULL,
    kafka_topic TEXT NOT NULL,
    kafka_partition INTEGER NOT NULL,
    kafka_offset BIGINT NOT NULL,
    CONSTRAINT uq_raw_market_events_kafka_position
        UNIQUE (kafka_topic, kafka_partition, kafka_offset)
);

-- Indexes for common Bronze inspection queries.
CREATE INDEX IF NOT EXISTS idx_raw_market_events_symbol_event_time
    ON bronze.raw_market_events (symbol, event_time);

CREATE INDEX IF NOT EXISTS idx_raw_market_events_ingestion_time
    ON bronze.raw_market_events (ingestion_time);

-- Silver: one structured row per finalized symbol/interval/open-time candle.
CREATE TABLE IF NOT EXISTS silver.candles (
    symbol TEXT NOT NULL,
    "interval" TEXT NOT NULL,
    open_time TIMESTAMPTZ NOT NULL,
    close_time TIMESTAMPTZ NOT NULL,
    open_price NUMERIC NOT NULL,
    high_price NUMERIC NOT NULL,
    low_price NUMERIC NOT NULL,
    close_price NUMERIC NOT NULL,
    volume NUMERIC NOT NULL,
    is_closed BOOLEAN NOT NULL,
    CONSTRAINT pk_silver_candles
        PRIMARY KEY (symbol, "interval", open_time)
);

